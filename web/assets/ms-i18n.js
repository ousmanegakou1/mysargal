  /* ── Choix de la langue ───────────────────────────────────── */
  function detecter() {
    try {
      var p = new URLSearchParams(location.search).get('lang');
      if (p && DICO[p]) { localStorage.setItem('ms_lang', p); return p; }
      if (p === 'fr') { localStorage.setItem('ms_lang', 'fr'); return 'fr'; }
      var m = localStorage.getItem('ms_lang');
      if (m && (DICO[m] || m === 'fr')) return m;
    } catch (e) {}
    var n = ((navigator.language || navigator.userLanguage || 'fr') + '').slice(0, 2).toLowerCase();
    return DICO[n] ? n : 'fr';
  }

  var LANGUE = detecter();
  var TABLE = DICO[LANGUE] || null;

  /* ── Traduction d'une chaîne isolée ───────────────────────── */
  function T(fr) {
    if (!TABLE) return fr;
    var t = String(fr == null ? '' : fr).trim();
    return Object.prototype.hasOwnProperty.call(TABLE, t) ? TABLE[t] : fr;
  }

  /* ── Traduction du rendu ──────────────────────────────────── */
  var IGNORER = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, CODE: 1, PRE: 1, SVG: 1 };

  function traduireNoeuds(racine) {
    if (!TABLE || !racine) return;
    var it = document.createTreeWalker(racine, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        var p = n.parentNode;
        if (p && IGNORER[p.nodeName]) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    var lot = [], n;
    while ((n = it.nextNode())) lot.push(n);
    for (var i = 0; i < lot.length; i++) {
      var brut = lot[i].nodeValue;
      var cle = brut.trim();
      if (Object.prototype.hasOwnProperty.call(TABLE, cle)) {
        // On conserve les espaces autour, pour ne pas coller les mots voisins.
        lot[i].nodeValue = brut.replace(cle, TABLE[cle]);
      }
    }
  }

  var ATTRS = ['placeholder', 'title', 'alt', 'aria-label'];
  function traduireAttributs(racine) {
    if (!TABLE || !racine || !racine.querySelectorAll) return;
    for (var a = 0; a < ATTRS.length; a++) {
      var nom = ATTRS[a];
      var els = racine.querySelectorAll('[' + nom + ']');
      for (var i = 0; i < els.length; i++) {
        var v = els[i].getAttribute(nom);
        if (v && Object.prototype.hasOwnProperty.call(TABLE, v.trim())) {
          els[i].setAttribute(nom, TABLE[v.trim()]);
        }
      }
    }
  }

  function traduire(racine) {
    racine = racine || document.body;
    traduireNoeuds(racine);
    traduireAttributs(racine);
  }

  /* ── Redéclenchement après chaque rendu ───────────────────── */
  var enAttente = false;
  function planifier() {
    if (enAttente) return;
    enAttente = true;
    requestAnimationFrame(function () {
      enAttente = false;
      observateur && observateur.disconnect();
      try { traduire(document.body); } catch (e) {}
      brancher();
    });
  }

  var observateur = null;
  function brancher() {
    if (!TABLE || !document.body || !window.MutationObserver) return;
    observateur = new MutationObserver(planifier);
    observateur.observe(document.body, { childList: true, subtree: true, characterData: true });
  }

  function demarrer() {
    if (!TABLE) return;             // français : rien à faire
    document.documentElement.lang = LANGUE;
    traduire(document.body);
    brancher();
  }

  function demarrerAvecSelecteur() {
    try { demarrer(); } catch (e) {}
    try { poserSelecteur(); } catch (e) {}
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', demarrerAvecSelecteur);
  } else {
    demarrerAvecSelecteur();
  }


  /* ── Sélecteur de langue ──────────────────────────────────────
     Le mécanisme de changement existait déjà, mais aucune page ne
     l'affichait : il fallait taper ?lang=en à la main. Il est maintenant
     injecté par cette couche, donc présent partout où elle est chargée.
     Une page peut s'en passer avec <body data-ms-langue="non">.
     ─────────────────────────────────────────────────────────── */
  // Le sélecteur est désormais un composant partagé, identique partout :
  // même endroit, même geste, sur la landing comme dans les consoles.
  function poserSelecteur() {
    if (!document.body) return;
    if (document.body.getAttribute('data-ms-langue') === 'non') return;
    if (!window.msLangue) return;
    window.msLangue.poser({ courante: LANGUE });
  }

  /* ── Interface publique ───────────────────────────────────── */
  window.msI18n = {
    langue: LANGUE,
    T: T,
    traduire: traduire,
    changer: function (l) {
      try { localStorage.setItem('ms_lang', l); } catch (e) {}
      location.reload();
    },
    langues: ['fr', 'en', 'es'],
  };
